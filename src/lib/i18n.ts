/**
 * RTL-ready i18n foundation.
 * Every string used in the UI flows through `t()`, and the app reads the
 * direction from the active locale, so layout mirrors automatically.
 * All spacing uses logical CSS utilities (ps-/pe-/ms-/me- / start/end).
 */

export const locales = ["en", "ar"] as const;
export type Locale = (typeof locales)[number];
export const DEFAULT_LOCALE: Locale = "en";
export const LOCALE_COOKIE = "app_locale";

export function dirFor(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function isLocale(value: string | undefined | null): value is Locale {
  return !!value && (locales as readonly string[]).includes(value);
}

